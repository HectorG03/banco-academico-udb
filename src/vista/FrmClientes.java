    private void btnCuentasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCuentasActionPerformed
        // TODO add your handling code here:
        int fila = tblClientes.getSelectedRow();
        if (fila < 0) {
            mostrarError("Seleccione un cliente primero para ver o crear sus cuentas.");
            return;
        }
        
        int codigoCliente = Integer.parseInt(txtCodigo.getText().trim());
        try {
            // Buscar el cliente completo 
            Cliente clienteSeleccionado = clienteServicio.buscarPorCodigo(codigoCliente);
            
            FrmCuentas panelCuentas = new FrmCuentas(clienteSeleccionado);
            panelCuentas.setBorder(javax.swing.BorderFactory.createLineBorder(java.awt.Color.GRAY, 1));

            javax.swing.JDialog dialogo = new javax.swing.JDialog(this, "Módulo de Cuentas", true);
            
            dialogo.setUndecorated(true); // desaparece la X
            dialogo.setDefaultCloseOperation(javax.swing.JDialog.DO_NOTHING_ON_CLOSE); // Alt+F4 tampoco cierra
            dialogo.setContentPane(panelCuentas);
            dialogo.pack();
            dialogo.setLocationRelativeTo(this);
            dialogo.setVisible(true);

        } catch (Exception e) {
            mostrarError("Error al abrir las cuentas: " + e.getMessage());
        }
    }//GEN-LAST:event_btnCuentasActionPerformed
    
