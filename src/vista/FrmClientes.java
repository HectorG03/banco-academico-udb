    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        try {
            Cliente c = leerFormulario();
            String error = clienteServicio.registrar(c);
            
            if (error != null) {
                mostrarError(error);
                return;
            }
            
            mostrarInfo("Cliente registrado exitosamente.");
            cargarTabla();
            limpiarFormulario();
        } catch (Exception e) {
            mostrarError("Ocurrió un error inesperado al guardar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        try {
            if (txtCodigo.getText().trim().isEmpty()) {
                mostrarError("Por favor, seleccione un cliente de la tabla para actualizar.");
                return;
            }
            
            Cliente c = leerFormulario();
            String error = clienteServicio.modificar(c);
            
            if (error != null) {
                mostrarError(error);
                return;
            }
            
            mostrarInfo("Cliente actualizado exitosamente.");
            cargarTabla();
            limpiarFormulario();
        } catch (Exception e) {
            mostrarError("Ocurrió un error inesperado al actualizar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnCambiarEstadoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCambiarEstadoActionPerformed
        // TODO add your handling code here:
        try {
            int fila = tblClientes.getSelectedRow();
            if (fila < 0) {
                mostrarError("Seleccione un cliente de la tabla para cambiar su estado.");
                return;
            }
            
            int codigo = Integer.parseInt(txtCodigo.getText().trim());
            EstadoCliente nuevoEstado = (EstadoCliente) cbEstado.getSelectedItem();
                        
            int confirmacion = JOptionPane.showConfirmDialog(
                this, 
                "¿Está seguro de cambiar el estado del cliente?", 
                "Confirmar cambio de estado", 
                JOptionPane.YES_NO_OPTION
            );
            
            if (confirmacion == JOptionPane.YES_OPTION) {
                
                String error = clienteServicio.cambiarEstado(codigo, nuevoEstado);
                if (error != null) {
                    mostrarError(error);
                    return;
                }
                
                mostrarInfo("Estado actualizado correctamente.");
                cargarTabla();
                limpiarFormulario();
            }
        } catch (Exception e) {
            mostrarError("Error al cambiar el estado: " + e.getMessage());
        }
    }//GEN-LAST:event_btnCambiarEstadoActionPerformed

