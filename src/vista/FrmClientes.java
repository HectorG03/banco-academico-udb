    private void configurarTabla() {
        // no permitir que las celdas sean editables
        modeloTabla = new DefaultTableModel(
            new Object[]{"Código", "DUI", "Nombre", "Teléfono", "Correo", "Dirección", "Estado"}, 0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; // Celdas bloqueadas para edición manual
            }
        };
        tblClientes.setModel(modeloTabla);
    }
    
    private void cargarTabla() {
        try {
            modeloTabla.setRowCount(0); // Limpiar tabla
            List<Cliente> lista = clienteServicio.listarClientes();
            for (Cliente c : lista) {
                modeloTabla.addRow(new Object[]{
                    c.getCodigoCliente(),
                    c.getDui(),
                    c.getNombre(),
                    c.getTelefono(),
                    c.getCorreo(),
                    c.getDireccion(),
                    c.getEstado()
                });
            }
        } catch (Exception e) {
            mostrarError("Error al cargar los clientes: " + e.getMessage());
        }
    }
    
    private void limpiarFormulario() {
        txtCodigo.setText("");
        txtDui.setText("");
        txtNombre.setText("");
        txtTelefono.setText("");
        txtCorreo.setText("");
        txtDireccion.setText("");
        if (cbEstado.getItemCount() > 0) {
            cbEstado.setSelectedIndex(0);
        }
        tblClientes.clearSelection();
    }
    
    private Cliente leerFormulario() {
        Cliente c = new Cliente();
        
        // Si hay código en el campo (al actualizar), se lo asignamos
        if (!txtCodigo.getText().trim().isEmpty()) {
            c.setCodigoCliente(Integer.parseInt(txtCodigo.getText().trim()));
        }
        
        c.setDui(txtDui.getText().trim());
        c.setNombre(txtNombre.getText().trim());
        c.setTelefono(txtTelefono.getText().trim());
        c.setCorreo(txtCorreo.getText().trim());
        c.setDireccion(txtDireccion.getText().trim());
        
        if (cbEstado.getSelectedItem() != null) {
            c.setEstado((EstadoCliente) cbEstado.getSelectedItem());
        }
        
        return c;
    }

    private void seleccionarClienteDeTabla() {
        int fila = tblClientes.getSelectedRow();
        if (fila >= 0) {
            txtCodigo.setText(modeloTabla.getValueAt(fila, 0).toString());
            txtDui.setText(modeloTabla.getValueAt(fila, 1).toString());
            txtNombre.setText(modeloTabla.getValueAt(fila, 2).toString());
            txtTelefono.setText(modeloTabla.getValueAt(fila, 3).toString());
            txtCorreo.setText(modeloTabla.getValueAt(fila, 4).toString());
            txtDireccion.setText(modeloTabla.getValueAt(fila, 5).toString());
            cbEstado.setSelectedItem(modeloTabla.getValueAt(fila, 6));
        }
    }

